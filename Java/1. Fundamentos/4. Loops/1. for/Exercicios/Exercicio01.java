// ## Exercicio 01. Contagem de 1 a 10

// **Enunciado:** Escreva um programa em Java utilizando um loop `for` que imprima todos os números de 1 até 10, em ordem crescente.


public class Exercicio01 {
    public static void main(String[] args) {
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }
    }
}
